#!/usr/bin/env python3
"""P00 development HOST DATA bootstrap: scope, SQLite backup and restore drill.

This utility configures durable storage for the EXISTING read-only observer.
It does NOT start it, call Ollama, run model-written code, change GitHub,
or install OS services. Host provisioning requires a separately authorized
operator; GitHub Actions can exercise it only against disposable fixtures.
"""
from __future__ import annotations

import argparse
from contextlib import closing
import hashlib
import json
import os
import re
import secrets
import sqlite3
import stat
import sys
from datetime import datetime, timezone
from pathlib import Path

from tools.phase_controller import EventJournal
from tools.phase_worker import WorkerLease
from tools.workspace_policy import _has_symlink_component, _inside

_BACKUP_NAME = re.compile(r"^controller-[0-9]{8}T[0-9]{6}Z-[a-f0-9]{12}\.sqlite$")
_STATE_FILE = "controller.db"
_HOST_MARKER = "host.json"


class HostBootstrapError(ValueError):
    """Local storage and recovery not proven safe; no deployment authorized."""


def _assert_directory(path: Path, *, existing: bool = True) -> Path:
    if not path.is_absolute() or path == path.parent:
        raise HostBootstrapError("absolute non-root directory required")
    if _has_symlink_component(path):
        raise HostBootstrapError("host path contains symlink or junction")
    if existing and not path.is_dir():
        raise HostBootstrapError("required directory missing")
    return path.resolve(strict=existing)


def _permission_check(path: Path) -> bool:
    """POSIX-only mode check; never claim Windows ACL verification."""
    if os.name != "posix":
        return False
    mode = stat.S_IMODE(path.stat().st_mode)
    return not bool(mode & 0o077)


def _sqlite_integrity(path: Path) -> dict:
    if not path.is_file() or _has_symlink_component(path):
        raise HostBootstrapError("SQLite file missing or linked")
    try:
        with closing(sqlite3.connect(path.as_uri() + "?mode=ro", uri=True, timeout=5)) as db:
            result = db.execute("PRAGMA integrity_check").fetchone()
            if result != ("ok",):
                raise HostBootstrapError("SQLite integrity failed")
            objects = {
                row[0] for row in db.execute(
                    "SELECT name FROM sqlite_master WHERE type='table'"
                ).fetchall()
            }
            if not {"phase_events", "worker_leases"} <= objects:
                raise HostBootstrapError("required observer tables missing")
            events = int(db.execute("SELECT COUNT(*) FROM phase_events").fetchone()[0])
            return {"integrity": "PASS", "event_count": events}
    except sqlite3.Error:
        raise HostBootstrapError("SQLite integrity check could not complete") from None


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as inp:
        for chunk in iter(lambda: inp.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


class HostLayout:
    """Trusted operator-chosen path layout (never generated by model output)."""

    def __init__(self, checkout: Path, host_root: Path):
        checkout = _assert_directory(Path(checkout), existing=True)
        host_root = _assert_directory(Path(host_root), existing=False)
        if checkout == host_root or _inside(checkout, host_root) or _inside(host_root, checkout):
            raise HostBootstrapError("host state must be outside the source checkout")
        if not (checkout / "AGENTS.md").is_file() or not (checkout / "docs/state/PHASE.json").is_file():
            raise HostBootstrapError("source checkout is not the expected project")
        if _has_symlink_component(checkout / "docs/state/PHASE.json"):
            raise HostBootstrapError("source state file linked")
        try:
            phase = json.loads((checkout / "docs/state/PHASE.json").read_text(encoding="utf-8"))
        except (OSError, ValueError, UnicodeError):
            raise HostBootstrapError("phase metadata unreadable") from None
        if not isinstance(phase, dict) or (
            phase.get("phase") != "P00" or
            phase.get("phase_status") != "IN_PROGRESS" or
            phase.get("active_branch") != "phase/00-governance" or
            phase.get("primary_pr") != 1
        ):
            raise HostBootstrapError("host bootstrap is restricted to active P00")
        self.checkout = checkout
        self.root = host_root
        self.state = host_root / "state"
        self.backups = host_root / "backups"
        self.db = self.state / _STATE_FILE
        self.marker = self.root / _HOST_MARKER

    def _ensure_initialized(self) -> None:
        for d in (self.root, self.state, self.backups):
            _assert_directory(d)
            if not _permission_check(d) and os.name == "posix":
                raise HostBootstrapError("host directory permissions not restricted")
        if not self.marker.is_file() or _has_symlink_component(self.marker):
            raise HostBootstrapError("host metadata missing")
        try:
            raw = json.loads(self.marker.read_text(encoding="utf-8"))
        except (ValueError, OSError, UnicodeError):
            raise HostBootstrapError("host metadata corrupt") from None
        if not isinstance(raw, dict) or raw != {
            "schema": 1, "phase": "P00", "worker_type": "READ_ONLY_OBSERVER",
            "github_write_capability": False,
        }:
            raise HostBootstrapError("host metadata disagrees with policy")
        if os.name == "posix" and not _permission_check(self.marker):
            raise HostBootstrapError("host metadata permissions not restricted")

    def initialize(self, *, authorized: bool = False) -> dict:
        """Explicit host provisioning; never writes into repo or launches process."""
        if not authorized:
            raise HostBootstrapError("host initialization requires operator authorization")
        if self.root.exists() and not self.root.is_dir():
            raise HostBootstrapError("host root is not a directory")
        for d in (self.root, self.state, self.backups):
            if _has_symlink_component(d):
                raise HostBootstrapError("host path linked")
            d.mkdir(mode=0o700, parents=False, exist_ok=True)
            if os.name == "posix":
                d.chmod(0o700)
        if self.marker.exists() or self.db.exists():
            raise HostBootstrapError("existing host state requires verification, not reinitialization")
        # The two components intentionally share a single durable WAL database.
        EventJournal(self.db)
        WorkerLease(self.db)
        if os.name == "posix":
            self.db.chmod(0o600)
        payload = {
            "schema": 1, "phase": "P00", "worker_type": "READ_ONLY_OBSERVER",
            "github_write_capability": False,
        }
        fd = os.open(self.marker, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as out:
                json.dump(payload, out, sort_keys=True)
                out.write("\n")
                out.flush()
                os.fsync(out.fileno())
        except BaseException:
            self.marker.unlink(missing_ok=True)
            raise
        self._ensure_initialized()
        check = _sqlite_integrity(self.db)
        return {
            "result": "HOST_STORAGE_INITIALIZED",
            "phase": "P00",
            "db_integrity": check["integrity"],
            "worker_running_verified": False,
            "os_sandbox_verified": False,
            "model_usable_verified": False,
            "windows_acl_verified": False,
            "github_writes": 0,
        }

    def verify(self) -> dict:
        self._ensure_initialized()
        check = _sqlite_integrity(self.db)
        if os.name == "posix" and not _permission_check(self.db):
            raise HostBootstrapError("host DB permissions not restricted")
        return {
            "result": "HOST_STORAGE_VERIFIED",
            "phase": "P00", "db_integrity": check["integrity"],
            "event_count": check["event_count"],
            "posix_file_permissions_verified": os.name == "posix",
            "windows_acl_verified": False,
            "worker_running_verified": False,
            "os_sandbox_verified": False,
            "github_writes": 0,
        }

    def backup(self) -> dict:
        """SQLite online backup API copies the WAL-consistent DB into new file."""
        self.verify()
        time_label = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        name = f"controller-{time_label}-{secrets.token_hex(6)}.sqlite"
        target = self.backups / name
        pending = self.backups / (".backup-" + secrets.token_hex(12) + ".tmp")
        if target.exists() or pending.exists() or _has_symlink_component(pending):
            raise HostBootstrapError("backup target collision or linked path")
        fd = os.open(pending, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        os.close(fd)
        try:
            with closing(sqlite3.connect(self.db, timeout=15)) as source, closing(sqlite3.connect(pending, timeout=15)) as dest:
                source.backup(dest, pages=128, sleep=0.05)
            _sqlite_integrity(pending)
            # Windows CRT _commit may reject read-only descriptors.
            # Flush the completed snapshot through a read/write handle.
            with pending.open("r+b") as inp:
                os.fsync(inp.fileno())
            digest = _sha256_file(pending)
            os.replace(pending, target)
            # Separate metadata cannot contain original credentials or paths.
            receipt_path = self.backups / (name + ".sha256")
            fd = os.open(receipt_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "w", encoding="ascii") as out:
                out.write(digest + "\n")
                out.flush()
                os.fsync(out.fileno())
            result = self.verify_backup(name)
            return {"result": "BACKUP_VERIFIED", "backup_name": name,
                    "sha256": digest, "restore_drill": result["result"],
                    "github_writes": 0, "worker_running_verified": False}
        finally:
            pending.unlink(missing_ok=True)

    def verify_backup(self, name: str) -> dict:
        """Read/restore into a disposable SQLite DB; NEVER overwrite live data."""
        self._ensure_initialized()
        if not isinstance(name, str) or not _BACKUP_NAME.fullmatch(name):
            raise HostBootstrapError("invalid backup filename")
        backup = self.backups / name
        digest_file = self.backups / (name + ".sha256")
        if any(_has_symlink_component(p) or not p.is_file() for p in (backup, digest_file)):
            raise HostBootstrapError("backup or digest file missing/linked")
        digest = digest_file.read_text(encoding="ascii").strip()
        if not re.fullmatch(r"[a-f0-9]{64}", digest):
            raise HostBootstrapError("backup digest malformed")
        actual = _sha256_file(backup)
        if not secrets.compare_digest(digest, actual):
            raise HostBootstrapError("backup digest mismatch")
        _sqlite_integrity(backup)
        drill = self.backups / (".restore-" + secrets.token_hex(12) + ".tmp")
        fd = os.open(drill, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        os.close(fd)
        try:
            with closing(sqlite3.connect(backup.as_uri() + "?mode=ro", uri=True, timeout=10)) as source, closing(sqlite3.connect(drill)) as dest:
                source.backup(dest)
            restored = _sqlite_integrity(drill)
            return {"result": "RESTORE_DRILL_PASSED",
                    "backup_name": name, "event_count": restored["event_count"],
                    "live_db_overwritten": False, "github_writes": 0}
        finally:
            drill.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description="P00 host SQLite storage, backup and recovery (no worker execution)")
    parser.add_argument("--repo-root", type=Path, required=True)
    parser.add_argument("--host-root", type=Path, required=True)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("inspect")
    sub.add_parser("initialize")
    sub.add_parser("backup")
    verify = sub.add_parser("verify-backup")
    verify.add_argument("--name", required=True)
    args = parser.parse_args()
    try:
        layout = HostLayout(args.repo_root, args.host_root)
        if args.command == "inspect":
            result = layout.verify()
        elif args.command == "initialize":
            result = layout.initialize(
                authorized=(os.environ.get("ZYNOA_HOST_INIT_ALLOWED") == "1")
            )
        elif args.command == "backup":
            result = layout.backup()
        else:
            result = layout.verify_backup(args.name)
        print(json.dumps(result, sort_keys=True))
        return 0
    except (HostBootstrapError, OSError, sqlite3.Error, UnicodeError, ValueError) as exc:
        print(json.dumps({"result": "BLOCKED", "error_class": type(exc).__name__,
                          "credentials_echoed": False, "worker_running_verified": False}))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
